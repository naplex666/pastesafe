/**
 * PasteSafe — Markdown export for a triaged report.
 * Exported files contain REDACTED text only.
 */

import type { SavedReport } from './store';

export function reportToMarkdown(report: SavedReport): string {
  const lines: string[] = [];
  const date = new Date(report.createdAt).toISOString();
  const t = report.triage;

  lines.push(`# PasteSafe report — ${t?.title ?? 'Untitled finding'}`);
  lines.push('');
  lines.push(`- **Created:** ${date}`);
  lines.push(`- **Mode:** ${report.mode}`);
  lines.push(
    `- **Secrets redacted on-device:** ${report.findings.length}`,
  );
  if (t) {
    lines.push(`- **Severity:** ${t.severity.toUpperCase()}`);
    lines.push(`- **CVSS:** ${t.cvssVector} (${t.cvssScore.toFixed(1)})`);
    lines.push(`- **Category:** ${t.category}`);
    lines.push('');
    lines.push('## Summary');
    lines.push('');
    lines.push(t.summary);
    lines.push('');
    if (t.remediation.length > 0) {
      lines.push('## Remediation');
      lines.push('');
      for (const step of t.remediation) lines.push(`- ${step}`);
      lines.push('');
    }
  }
  lines.push('## Redacted report (safe to share)');
  lines.push('');
  lines.push('```');
  lines.push(report.redactedText);
  lines.push('```');
  lines.push('');
  if (report.findings.length > 0) {
    lines.push('## Redacted items');
    lines.push('');
    for (const f of report.findings) {
      lines.push(
        `- ${f.label} (${f.severity}): \`${f.masked}\` → \`${f.placeholder}\``,
      );
    }
    lines.push('');
  }
  lines.push('---');
  lines.push(
    '_Generated by PasteSafe — secrets were redacted on-device before any AI analysis. Only redacted text was sent to the cloud._',
  );
  return lines.join('\n');
}

export function downloadText(filename: string, text: string): void {
  const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
